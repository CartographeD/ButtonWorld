class Country {
  final String name;
  final String code;

  const Country({
    required this.name,
    required this.code,
  });

  String get flag {
    if (code.length != 2) {
      return '🌍';
    }

    return String.fromCharCodes(
      code.toUpperCase().codeUnits.map(
        (char) => char + 127397,
      ),
    );
  }
}

